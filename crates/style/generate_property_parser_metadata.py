    text=p.read_text()
    for (prop,),body,line in functions(text,r'const CSSValue\* (\w+)::ParseSingleValue\([^)]*\) const \{'):
        if prop in seen: continue
        b=re.sub(r'//[^\n]*','',body).strip()
        # Admit complete one-return consumer bodies only. Parameters select the
        # source range and quirks policy, never inferred from property names.
        m=re.fullmatch(r'return (?:css_parsing_utils::)?((?:Consume|Parse)\w+)\((.*?)\);',b,re.S)
        if not m: continue
