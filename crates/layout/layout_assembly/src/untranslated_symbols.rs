//! Link-time definitions for LayoutNG functions that the reduced LayoutNG
//! source snapshot declares (`extern` blocks in layout_core, layout_style,
//! layout_algo_inline, ...) but never defines, because their Chromium bodies
//! have not been translated.
//!
//! Only unreachable code references them: macOS ld64 and lld dead-strip those
//! callers before resolving symbols, while MSVC link.exe requires every
//! referenced external to exist. Each stub aborts with the symbol's name, so a
//! call that becomes reachable fails loudly instead of linking to garbage.
//! Translating a function from Chromium means deleting its name here.

#[cold]
#[inline(never)]
fn untranslated(name: &str) -> ! {
    eprintln!("untranslated LayoutNG symbol called: {name}");
    std::process::abort()
}

// The declarations' parameters are irrelevant: the stub never reads them and
// never returns.
macro_rules! untranslated {
    ($($name:ident),* $(,)?) => {
        $(
            #[unsafe(no_mangle)]
            pub extern "C" fn $name() -> ! {
                untranslated(stringify!($name))
            }
        )*
    };
}

