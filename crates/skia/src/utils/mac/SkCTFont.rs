pub fn SkCTFontGetSmoothBehavior() -> SkCTFontSmoothBehavior {
    static BEHAVIOR: OnceLock<SkCTFontSmoothBehavior> = OnceLock::new();
    *BEHAVIOR.get_or_init(|| unsafe {
        let mut no_smooth = [[0u32; 16]; 16];
        let mut smooth = [[0u32; 16]; 16];
        let color_space = SkUniqueCFRef::from_raw(CGColorSpaceCreateDeviceRGB());
        let no_context = SkUniqueCFRef::from_raw(CGBitmapContextCreate(
            no_smooth.as_mut_ptr().cast(),
            16,
            16,
            8,
            16 * 4,
            color_space.get(),
            kBitmapInfoRGB,
        ));
        let smooth_context = SkUniqueCFRef::from_raw(CGBitmapContextCreate(
            smooth.as_mut_ptr().cast(),
            16,
            16,
            8,
            16 * 4,
            color_space.get(),
            kBitmapInfoRGB,
        ));
        // SDK kCFAllocatorDefault is null; kCFAllocatorNull prevents releasing
        // the actual static spider bytes. Unique CF owners release in reverse
        // construction order before either stack-backed pixel array goes away.
        let data = SkUniqueCFRef::from_raw(CFDataCreateWithBytesNoCopy(
            core::ptr::null(),
            kSpiderSymbol_ttf.as_ptr(),
            kSpiderSymbol_ttf.len() as isize,
            kCFAllocatorNull,
        ));
        let descriptor =
            SkUniqueCFRef::from_raw(CTFontManagerCreateFontDescriptorFromData(data.get()));
        let font = SkUniqueCFRef::from_raw(CTFontCreateWithFontDescriptor(
            descriptor.get(),
            16.0,
            core::ptr::null(),
        ));
        debug_assert!(!font.is_null());
        CGContextSetShouldSmoothFonts(no_context.get(), false);
        CGContextSetShouldAntialias(no_context.get(), true);
        CGContextSetTextDrawingMode(no_context.get(), kCGTextFill);
        CGContextSetGrayFillColor(no_context.get(), 1.0, 1.0);
        CGContextSetShouldSmoothFonts(smooth_context.get(), true);
        CGContextSetShouldAntialias(smooth_context.get(), true);
        CGContextSetTextDrawingMode(smooth_context.get(), kCGTextFill);
        CGContextSetGrayFillColor(smooth_context.get(), 1.0, 1.0);
        let point = CGPoint { x: 0.0, y: 3.0 };
        let spider = 3u16;
        CTFontDrawGlyphs(font.get(), &spider, &point, 1, no_context.get());
        CTFontDrawGlyphs(font.get(), &spider, &point, 1, smooth_context.get());
        let mut behavior = SkCTFontSmoothBehavior::none;
        for x in 0..16 {
            for y in 0..16 {
                let pixel = smooth[x][y];
                let r = (pixel >> 16) & 0xFF;
                let g = (pixel >> 8) & 0xFF;
                let b = pixel & 0xFF;
                if r != g || r != b {
                    return SkCTFontSmoothBehavior::subpixel;
                }
                if no_smooth[x][y] != pixel {
                    behavior = SkCTFontSmoothBehavior::some;
                }
            }
        }
        behavior
    })
}

