pub fn SkCTFontGetNSFontWeightMapping() -> &'static SkCTFontWeightMapping {
    static DEFAULT: [CGFloat; 11] = [
        -1.00, -0.80, -0.60, -0.40, 0.00, 0.23, 0.30, 0.40, 0.56, 0.62, 1.00,
    ];
    const NAMES: [&[u8]; 9] = [
        b"NSFontWeightUltraLight\0",
        b"NSFontWeightThin\0",
        b"NSFontWeightLight\0",
        b"NSFontWeightRegular\0",
        b"NSFontWeightMedium\0",
        b"NSFontWeightSemibold\0",
        b"NSFontWeightBold\0",
        b"NSFontWeightHeavy\0",
        b"NSFontWeightBlack\0",
    ];
    // None retains the genuine source fallback selection after any symbol miss;
    // a partially populated system array never becomes selected or escapes.
    static SELECTED: OnceLock<Option<SkCTFontWeightMapping>> = OnceLock::new();
    match SELECTED.get_or_init(|| {
        let mut weights = [0.0; 11];
        let mut i = 0;
        weights[i] = -1.0;
        i += 1;
        for name in NAMES {
            let pointer = unsafe { dlsym(RTLD_DEFAULT, name.as_ptr().cast()) };
            if pointer.is_null() {
                return None;
            }
            weights[i] = unsafe { pointer.cast::<CGFloat>().read() };
            i += 1;
        }
        weights[i] = 1.0;
        Some(weights)
    }) {
        Some(weights) => weights,
        None => &DEFAULT,
    }
}

