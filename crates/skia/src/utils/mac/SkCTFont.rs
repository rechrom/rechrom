pub fn SkCTFontGetDataFontWeightMapping() -> &'static SkCTFontWeightMapping {
    use crate::src::sfnt::SkOTTable_OS_2::SkOTTableOS2;
    use crate::src::sfnt::SkOTTable_OS_2_V0::SkOTTableOS2_V0;
    use crate::src::sfnt::SkSFNTHeader::{SkSFNTHeader, TableDirectoryEntry};
    static DEFAULT: SkCTFontWeightMapping = [
        -1.00, -0.70, -0.50, -0.23, 0.00, 0.20, 0.30, 0.40, 0.60, 0.80, 1.00,
    ];
    static SELECTED: OnceLock<Option<SkCTFontWeightMapping>> = OnceLock::new();
    match SELECTED.get_or_init(|| unsafe {
        let size = kSpiderSymbol_ttf.len();
        let data =
            crate::src::core::SkData::SkData::MakeWithCopy(kSpiderSymbol_ttf.as_ptr().cast(), size);
        let header = data.data().cast::<SkSFNTHeader>();
        // Native SkTAfter uses sizeof the genuine packed header. Neither table
        // position nor the OS/2 weight offset is guessed or hardcoded here.
        let entries = header
            .cast::<u8>()
            .add(core::mem::size_of::<SkSFNTHeader>())
            .cast::<TableDirectoryEntry>();
        let mut os2_entry: *const TableDirectoryEntry = core::ptr::null();
        let count = u16::from_be(core::ptr::addr_of!((*header).numTables).read_unaligned());
        for i in 0..count as usize {
            let entry = entries.add(i);
            if SkOTTableOS2::TAG == core::ptr::addr_of!((*entry).tag).read_unaligned() {
                os2_entry = entry;
                break;
            }
        }
        if os2_entry.is_null() {
            return None;
        }
        let offset =
            u32::from_be(core::ptr::addr_of!((*os2_entry).offset).read_unaligned()) as usize;
        let os2 = data.writable_data().add(offset).cast::<SkOTTableOS2_V0>();
        const LOWEST_USEFUL_WEIGHT_CLASS: u16 = 11;
        let mut previous = -CGFloat::MAX;
        let mut weights = [0.0; 11];
        for i in 0..11 {
            let weight_class = if i == 0 {
                LOWEST_USEFUL_WEIGHT_CLASS
            } else {
                (i * 100) as u16
            };
            core::ptr::addr_of_mut!((*os2).usWeightClass.value)
                .write_unaligned(weight_class.to_be());
            // Each iteration must copy. Older CoreText caches by CFData byte
            // pointer, so sharing the changing backing would alter native results.
            let cf_data = SkUniqueCFRef::from_raw(CFDataCreate(
                core::ptr::null(),
                data.data(),
                data.size() as isize,
            ));
            if cf_data.is_null() {
                return None;
            }
            let descriptor =
                SkUniqueCFRef::from_raw(CTFontManagerCreateFontDescriptorFromData(cf_data.get()));
            if descriptor.is_null() {
                return None;
            }
            let font = SkUniqueCFRef::from_raw(CTFontCreateWithFontDescriptor(
                descriptor.get(),
                9.0,
                core::ptr::null(),
            ));
            if font.is_null() {
                return None;
            }
            let descriptor2 = SkUniqueCFRef::from_raw(CTFontCopyFontDescriptor(font.get()));
            if descriptor2.is_null() {
                return None;
            }
            let traits = SkUniqueCFRef::from_raw(CTFontDescriptorCopyAttribute(
                descriptor2.get(),
                kCTFontTraitsAttribute,
            ));
            if traits.is_null() || CFGetTypeID(traits.get()) != CFDictionaryGetTypeID() {
                return None;
            }
            let dictionary = traits.get().cast::<CFDictionary>();
            let mut weight_ref: *const c_void = core::ptr::null();
            if CFDictionaryGetValueIfPresent(dictionary, kCTFontWeightTrait.cast(), &mut weight_ref)
                == 0
                || weight_ref.is_null()
            {
                return None;
            }
            let mut weight = 0.0;
            if CFGetTypeID(weight_ref) == CFNumberGetTypeID() {
                let number = weight_ref.cast_mut().cast::<CFNumber>();
                if CFNumberIsFloatType(number) == 0
                    || CFNumberGetValue(
                        number,
                        kCFNumberCGFloatType,
                        (&mut weight as *mut CGFloat).cast(),
                    ) == 0
                {
                    // Native GetValue may write even on failure; its explicit
                    // fallback resets the value to zero before monotonic checking.
                    weight = 0.0;
                }
            }
            if weight <= previous {
                return None;
            }
            previous = weight;
            weights[i] = weight;
        }
        let slope = (weights[1] - weights[0]) / (100 - LOWEST_USEFUL_WEIGHT_CLASS) as CGFloat;
        weights[0] = weights[1] - (slope * 100.0);
        Some(weights)
    }) {
        Some(weights) => weights,
        None => &DEFAULT,
    }
}
