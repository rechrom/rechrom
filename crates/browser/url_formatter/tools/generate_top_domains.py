def tree(counts):
    nodes=[(count,character,None,None) for character,count in sorted(counts.items())]
    nodes.sort(key=lambda n:n[0])
    while len(nodes)>1:
        a,b=nodes[:2];nodes[:2]=[(a[0]+b[0],0,a,b)]
        nodes.sort(key=lambda n:n[0])
    return nodes[0]
def table(node,prefix=()):
    if node[2] is None:return {node[1]:prefix}
    return table(node[2],prefix+(0,)) | table(node[3],prefix+(1,))
def bits(value,count):return [(value>>i)&1 for i in range(count-1,-1,-1)]
def encode_size(n):
    if n<4:return [ [0,0],[1,0,0],[1,0,1],[1,1,0] ][n]
    return [n%2]+[1]*((n+1)//2)+[0]
def write(tbl, counts):
    output=[]
    def dispatch(rows):
        prefix=0
        while rows[0][0][prefix]!=0 and all(r[0][prefix]==rows[0][0][prefix] for r in rows):prefix+=1
        block=encode_size(prefix)
        def char(c):
            block.extend(tbl[c]);counts[c]+=1
        for c in rows[0][0][:prefix]:char(c)
        rows=[(name[prefix:],entry) for name,entry in rows]
        last=None
        while rows:
            candidate=rows[0][0][0];end=1
            while end<len(rows) and rows[end][0][0]==candidate:end+=1
            char(candidate)
            if candidate==0:
                assert end==1
