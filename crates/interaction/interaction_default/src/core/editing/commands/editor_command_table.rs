impl EditingCommandType {
    pub fn FromCommandName(name: &[u16]) -> Self {
        let lower = |unit: u16| {
            if (65..=90).contains(&unit) {
                unit + 32
            } else {
                unit
            }
        };
        match COMMAND_NAMES.binary_search_by(|(entry, _)| {
            entry
                .bytes()
                .map(u16::from)
                .map(lower)
                .cmp(name.iter().copied().map(lower))
        }) {
            Ok(index) => COMMAND_NAMES[index].1,
            Err(_) => Self::Invalid,
        }
    }
    pub fn Descriptor(self) -> Option<&'static EditorInternalCommand> {
        if self == Self::Invalid {
            None
        } else {
            Some(&EDITOR_COMMANDS[self as usize - 1])
        }
    }
}

