pub trait EditorCommandQueryContext {
    fn PasteSupported(&self) -> bool;
    fn ClipboardEnabled(
        &self,
        function: EnabledFunction,
        source: EditorCommandSource,
    ) -> Result<bool, &'static str>;
    fn CanReadClipboard(&self, source: EditorCommandSource) -> bool;
    fn CanWriteClipboard(&self, source: EditorCommandSource) -> bool;
    fn HasActiveEditContext(&self) -> bool;
    fn SelectionHasFocus(&self) -> bool;
    fn IsCaret(&self) -> bool;
    fn IsRange(&self) -> bool;
    fn CanEdit(&self) -> bool;
    fn CanEditRichly(&self) -> bool;
    fn HasMark(&self) -> bool;
    fn CanUndo(&self) -> bool;
    fn CanRedo(&self) -> bool;
    fn SelectAllEnabled(&self, source: EditorCommandSource) -> Result<bool, &'static str>;
}
impl EditorInternalCommand {
    pub fn IsSupported<C: EditorCommandQueryContext>(
        &self,
        c: &C,
        source: EditorCommandSource,
    ) -> bool {
        source == EditorCommandSource::kMenuOrKeyBinding
            || match self.is_supported_from_dom {
                SupportFunction::Supported => true,
                SupportFunction::SupportedFromMenuOrKeyBinding => false,
                SupportFunction::ClipboardCommands_PasteSupported => c.PasteSupported(),
            }
    }
    pub fn IsEnabled<C: EditorCommandQueryContext>(
        &self,
        c: &C,
        source: EditorCommandSource,
    ) -> Result<bool, &'static str> {
        if !self.IsSupported(c, source) {
            return Ok(false);
        }
        use EnabledFunction::*;
        match self.is_enabled {
            Enabled => return Ok(true),
            EnabledUndo => return Ok(c.CanUndo()),
            EnabledRedo => return Ok(c.CanRedo()),
            ClipboardCommands_EnabledCopy
            | ClipboardCommands_EnabledCut
            | ClipboardCommands_EnabledPaste => return c.ClipboardEnabled(self.is_enabled, source),
            _ => {}
        }
        if source == EditorCommandSource::kDom && c.HasActiveEditContext() {
            return Ok(false);
        }
        if self.is_enabled == EnabledSelectAll {
            return c.SelectAllEnabled(source);
        }
        let focus = source == EditorCommandSource::kDom || c.SelectionHasFocus();
        Ok(match self.is_enabled {
            EnabledInEditableText | EnabledInEditableTextOrCaretBrowsing | EnabledDelete => {
                source == EditorCommandSource::kMenuOrKeyBinding && c.HasActiveEditContext()
                    || focus && c.CanEdit()
            }
            EnabledInRichlyEditableText => focus && c.CanEditRichly(),
            EnabledRangeInRichlyEditableText | IsRemoveFormatAllowed => {
                focus && c.IsRange() && c.CanEditRichly()
            }
            EnabledVisibleSelection => focus && (c.IsRange() || c.IsCaret() && c.CanEdit()),
            EnabledVisibleSelectionAndMark => {
                focus && (c.IsRange() || c.IsCaret() && c.CanEdit()) && c.HasMark()
            }
            EnableCaretInEditableText => focus && c.IsCaret() && c.CanEdit(),
            EnabledUnselect => c.IsRange() || c.IsCaret() && c.CanEdit(),
            _ => false,
        })
    }
    pub fn CanExecute<C: EditorCommandQueryContext>(
        &self,
        c: &C,
        source: EditorCommandSource,
    ) -> Result<bool, &'static str> {
        if self.IsEnabled(c, source)? {
            return Ok(true);
        }
        Ok(self.IsSupported(c, source)
            && match self.can_execute {
                CanExecuteFunction::CanNotExecuteWhenDisabled => false,
                CanExecuteFunction::ClipboardCommands_CanWriteClipboard => {
                    c.CanWriteClipboard(source)
                }
                CanExecuteFunction::ClipboardCommands_CanReadClipboard => {
                    c.CanReadClipboard(source)
                }
            })
    }
}
