pub fn TidyUpHtmlStructure<C: DocumentCommandContext>(c: &C) -> Result<(), &'static str> {
    let current = c.DocumentElement();
    if !c.IsEditable(c.DocumentNode()) && !current.is_some_and(|node| c.IsEditable(node)) {
        return Ok(());
    }
    if current.is_some_and(|node| c.IsHTMLElement(node, "html")) {
        return Ok(());
    }
    let existing_head = current.filter(|node| c.IsHTMLElement(*node, "head"));
    let existing_body =
        current.filter(|node| c.IsHTMLElement(*node, "body") || c.IsHTMLElement(*node, "frameset"));
    let root = c.CreateHTMLElement("html")?;
    if let Some(head) = existing_head {
        c.AppendChild(root, head)?;
    }
    let body = match existing_body {
        Some(body) => body,
        None => c.CreateHTMLElement("body")?,
    };
    if let Some(current) = c.DocumentElement().filter(|current| *current != body) {
        c.AppendChild(body, current)?;
    }
    c.AppendChild(root, body)?;
    c.AppendChild(c.DocumentNode(), root)
}
